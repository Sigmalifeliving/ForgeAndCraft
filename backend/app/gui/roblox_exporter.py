# 2. ROBLOX STUDIO XML MODEL (.RBXM) GENERATOR
# -------------------------------------------------------------

def generate_rbxm_xml(gui_spec: dict[str, Any]) -> bytes:
    """Generates a valid Roblox Studio XML Model (.rbxm) file that can be inserted into StarterGui."""
    root = ET.Element("roblox")
    root.set("xmlns:xmime", "http://www.w3.org/2005/05/xmlmime")
    root.set("xmlns:xsi", "http://www.w3.org/2001/XMLSchema-instance")
    root.set("xsi:noNamespaceSchemaLocation", "http://www.roblox.com/roblox.xsd")
    root.set("version", "4")

    referent_id = {"val": 0}

    def next_ref() -> str:
        referent_id["val"] += 1
        return f"RBX_{referent_id['val']}"

    def build_item_xml(el: dict[str, Any], parent_elem: ET.Element):
        comp_type = el.get("type", "Frame")
        name = el.get("name", comp_type)
        props = el.get("properties", {})

        item = ET.SubElement(parent_elem, "Item")
        item.set("class", comp_type)
        item.set("referent", next_ref())

        properties = ET.SubElement(item, "Properties")

        # Name
        prop_name = ET.SubElement(properties, "string")
        prop_name.set("name", "Name")
        prop_name.text = name

        # Size
        if "size" in props:
            s = props["size"]
            udim2 = ET.SubElement(properties, "UDim2")
            udim2.set("name", "Size")
            ET.SubElement(udim2, "XS").text = str(s[0])
            ET.SubElement(udim2, "XO").text = str(int(s[1]))
            ET.SubElement(udim2, "YS").text = str(s[2])
            ET.SubElement(udim2, "YO").text = str(int(s[3]))

        # Position
        if "position" in props:
            p = props["position"]
            udim2 = ET.SubElement(properties, "UDim2")
            udim2.set("name", "Position")
            ET.SubElement(udim2, "XS").text = str(p[0])
            ET.SubElement(udim2, "XO").text = str(int(p[1]))
            ET.SubElement(udim2, "YS").text = str(p[2])
            ET.SubElement(udim2, "YO").text = str(int(p[3]))

        # AnchorPoint
        if "anchorPoint" in props:
            a = props["anchorPoint"]
            vec2 = ET.SubElement(properties, "Vector2")
            vec2.set("name", "AnchorPoint")
            ET.SubElement(vec2, "X").text = str(a[0])
            ET.SubElement(vec2, "Y").text = str(a[1])

        # BackgroundColor3
        if "backgroundColor" in props:
            r, g, b = _hex_to_rgb(props["backgroundColor"])
            c3 = ET.SubElement(properties, "Color3")
            c3.set("name", "BackgroundColor3")
            ET.SubElement(c3, "R").text = str(r)
            ET.SubElement(c3, "G").text = str(g)
            ET.SubElement(c3, "B").text = str(b)

        # BackgroundTransparency
        if "backgroundTransparency" in props:
            bt = ET.SubElement(properties, "float")
            bt.set("name", "BackgroundTransparency")
            bt.text = str(props["backgroundTransparency"])

        # BorderSizePixel
        bsp = ET.SubElement(properties, "int")
        bsp.set("name", "BorderSizePixel")
        bsp.text = str(props.get("borderSizePixel", 0))

        # TextLabel / TextButton / TextBox specific
        if "text" in props:
            txt = ET.SubElement(properties, "string")
            txt.set("name", "Text")
            txt.text = str(props["text"])

        if "textColor" in props:
            r, g, b = _hex_to_rgb(props["textColor"])
            tc = ET.SubElement(properties, "Color3")
            tc.set("name", "TextColor3")
            ET.SubElement(tc, "R").text = str(r)
            ET.SubElement(tc, "G").text = str(g)
            ET.SubElement(tc, "B").text = str(b)

        if "textSize" in props:
            ts = ET.SubElement(properties, "float")
            ts.set("name", "TextSize")
            ts.text = str(props["textSize"])

        # UICorner
        if comp_type == "UICorner" and "cornerRadius" in props:
            cr = props["cornerRadius"]
            udim = ET.SubElement(properties, "UDim")
            udim.set("name", "CornerRadius")
            ET.SubElement(udim, "S").text = str(cr[0])
            ET.SubElement(udim, "O").text = str(int(cr[1]))

        # UIStroke
        if comp_type == "UIStroke":
            if "strokeColor" in props:
                r, g, b = _hex_to_rgb(props["strokeColor"])
                c = ET.SubElement(properties, "Color3")
                c.set("name", "Color")
                ET.SubElement(c, "R").text = str(r)
                ET.SubElement(c, "G").text = str(g)
                ET.SubElement(c, "B").text = str(b)
            if "strokeThickness" in props:
                th = ET.SubElement(properties, "float")
                th.set("name", "Thickness")
                th.text = str(props["strokeThickness"])

        # UIGridLayout
        if comp_type == "UIGridLayout":
            if "cellSize" in props:
                cs = props["cellSize"]
                udim2 = ET.SubElement(properties, "UDim2")
                udim2.set("name", "CellSize")
                ET.SubElement(udim2, "XS").text = str(cs[0])
                ET.SubElement(udim2, "XO").text = str(int(cs[1]))
                ET.SubElement(udim2, "YS").text = str(cs[2])
                ET.SubElement(udim2, "YO").text = str(int(cs[3]))
            if "cellPadding" in props:
                cp = props["cellPadding"]
                udim2 = ET.SubElement(properties, "UDim2")
                udim2.set("name", "CellPadding")
                ET.SubElement(udim2, "XS").text = str(cp[0])
                ET.SubElement(udim2, "XO").text = str(int(cp[1]))
                ET.SubElement(udim2, "YS").text = str(cp[2])
                ET.SubElement(udim2, "YO").text = str(int(cp[3]))

        # Children recursion
        for child in el.get("children", []):
            if isinstance(child, dict):
                build_item_xml(child, item)

    # Build ScreenGui root
    root_item = ET.SubElement(root, "Item")
    root_item.set("class", "ScreenGui")
    root_item.set("referent", next_ref())

    root_props = ET.SubElement(root_item, "Properties")
    p_name = ET.SubElement(root_props, "string")
    p_name.set("name", "Name")
    p_name.text = gui_spec.get("name", "ForgeCraftGui")

    p_reset = ET.SubElement(root_props, "bool")
    p_reset.set("name", "ResetOnSpawn")
    p_reset.text = "false"

    for child in gui_spec.get("children", []):
        if isinstance(child, dict):
            build_item_xml(child, root_item)

    # Attach companion LocalScript to the ScreenGui
    local_script = ET.SubElement(root_item, "Item")
    local_script.set("class", "LocalScript")
    local_script.set("referent", next_ref())
    ls_props = ET.SubElement(local_script, "Properties")
    ls_name = ET.SubElement(ls_props, "string")
    ls_name.set("name", "Name")
    ls_name.text = "GuiController"

    ls_code = ET.SubElement(ls_props, "ProtectedString")
    ls_code.set("name", "Source")
    ls_code.text = """--!strict
-- Auto-generated Interaction Controller
local TweenService = game:GetService("TweenService")
local screenGui = script.Parent

-- Close buttons dismissal
for _, desc in ipairs(screenGui:GetDescendants()) do
    if (desc:IsA("TextButton") or desc:IsA("ImageButton")) and string.find(string.lower(desc.Name), "close") then
        desc.MouseButton1Click:Connect(function()
            screenGui.Enabled = false
        end)
    end
end
"""

    rough_string = ET.tostring(root, "utf-8")
    reparsed = minidom.parseString(rough_string)
    return reparsed.toprettyxml(indent="  ", encoding="utf-8")


# -------------------------------------------------------------
# 3. ZIP PACKAGE BUILDER
# -------------------------------------------------------------

def generate_roblox_zip_package(gui_spec: dict[str, Any]) -> bytes:
    """Creates a complete downloadable ZIP containing .rbxm, .luau, and import README."""
    gui_name = gui_spec.get("name", "ForgeCraftGui")
    clean_name = re.sub(r"[^a-zA-Z0-9_-]", "_", gui_name)

    rbxm_bytes = generate_rbxm_xml(gui_spec)
    luau_code = generate_luau_script(gui_spec)

    readme_content = f"""# ForgeCraft Roblox GUI Package: {gui_name}

This package contains production-ready Roblox Studio UI assets generated by ForgeCraft AI.

## Quick Installation Guide (Roblox Studio)

### Method 1: Instant Drag & Drop (Recommended)
1. Open your Roblox game in **Roblox Studio**.
2. Open the **Explorer** window (`View` -> `Explorer`).
3. Find **StarterGui**.
4. Right-click **StarterGui** -> **Insert from File...**
5. Select `{clean_name}.rbxm` from this package.
6. Done! Your GUI is loaded with complete hierarchy, layout, styling, and controller script.

---

### Method 2: Scripted Creation via Command Bar or Script
1. Open the Roblox Studio **Command Bar** (`View` -> `Command Bar`).
2. Paste or require the contents of `Create_{clean_name}.luau`.
3. Press **Enter** to instantly build the GUI hierarchy into `PlayerGui`.

---

## Included Files
- `{clean_name}.rbxm`: Native Roblox Studio Model file containing the complete ScreenGui.
- `Create_{clean_name}.luau`: Self-contained Luau constructor script.
- `GuiSpec.json`: The source-of-truth ForgeCraft JSON specification.
"""

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{clean_name}/{clean_name}.rbxm", rbxm_bytes)
        zf.writestr(f"{clean_name}/Create_{clean_name}.luau", luau_code)
        zf.writestr(f"{clean_name}/GuiSpec.json", json.dumps(gui_spec, indent=2))
        zf.writestr(f"{clean_name}/README.md", readme_content)

    buffer.seek(0)
    return buffer.getvalue()

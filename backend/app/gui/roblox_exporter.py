# 1. LUAU SCRIPT GENERATOR
# -------------------------------------------------------------

def generate_luau_script(gui_spec: dict[str, Any]) -> str:
    """Generates an optimized, modular Luau script that creates the GUI and sets up interactivity."""
    gui_name = gui_spec.get("name", "ForgeCraftGui")
    lines = [
        "--!strict",
        f"-- Generated by ForgeCraft AI for Roblox Studio",
        f"-- GUI: {gui_name}",
        "",
        'local Players = game:GetService("Players")',
        'local TweenService = game:GetService("TweenService")',
        "",
        'local player = Players.LocalPlayer',
        'local playerGui = player:WaitForChild("PlayerGui")',
        "",
        "-- Create Root ScreenGui",
        f'local screenGui = Instance.new("ScreenGui")',
        f'screenGui.Name = "{gui_name}"',
        'screenGui.ResetOnSpawn = false',
        'screenGui.ZIndexBehavior = Enum.ZIndexBehavior.Sibling',
        'screenGui.Parent = playerGui',
        "",
        "local buttonsToAnimate = {}",
        "local closeButtons = {}",
        "local searchBoxes = {}",
        "local itemGrids = {}",
        "",
    ]

    counter = {"val": 0}

    def render_node(el: dict[str, Any], parent_var: str):
        comp_type = el.get("type", "Frame")
        name = el.get("name", comp_type)
        props = el.get("properties", {})
        counter["val"] += 1
        var_name = f"inst_{counter['val']}"

        lines.append(f'-- [{comp_type}] {name}')
        lines.append(f'local {var_name} = Instance.new("{comp_type}")')
        lines.append(f'{var_name}.Name = "{name}"')

        # Properties
        if "size" in props:
            s = props["size"]
            lines.append(f"{var_name}.Size = UDim2.new({s[0]}, {int(s[1])}, {s[2]}, {int(s[3])})")
        if "position" in props:
            p = props["position"]
            lines.append(f"{var_name}.Position = UDim2.new({p[0]}, {int(p[1])}, {p[2]}, {int(p[3])})")
        if "anchorPoint" in props:
            a = props["anchorPoint"]
            lines.append(f"{var_name}.AnchorPoint = Vector2.new({a[0]}, {a[1]})")
        if "backgroundColor" in props:
            lines.append(f"{var_name}.BackgroundColor3 = {_color3_luau(props['backgroundColor'])}")
        if "backgroundTransparency" in props:
            lines.append(f"{var_name}.BackgroundTransparency = {props['backgroundTransparency']}")
        if "borderSizePixel" in props:
            lines.append(f"{var_name}.BorderSizePixel = {props['borderSizePixel']}")
        else:
            if comp_type in ("Frame", "ScrollingFrame", "TextButton", "TextLabel", "TextBox"):
                lines.append(f"{var_name}.BorderSizePixel = 0")

        if "text" in props:
            safe_text = props["text"].replace('"', '\\"').replace("\n", "\\n")
            lines.append(f'{var_name}.Text = "{safe_text}"')
        if "textColor" in props:
            lines.append(f"{var_name}.TextColor3 = {_color3_luau(props['textColor'])}")
        if "textSize" in props:
            lines.append(f"{var_name}.TextSize = {props['textSize']}")
        if "font" in props:
            lines.append(f'{var_name}.Font = Enum.Font.{props["font"]}')
        if "cornerRadius" in props and comp_type == "UICorner":
            cr = props["cornerRadius"]
            lines.append(f"{var_name}.CornerRadius = UDim.new({cr[0]}, {int(cr[1])})")
        if comp_type == "UIStroke":
            if "strokeColor" in props:
                lines.append(f"{var_name}.Color = {_color3_luau(props['strokeColor'])}")
            if "strokeThickness" in props:
                lines.append(f"{var_name}.Thickness = {props['strokeThickness']}")
        if comp_type == "UIGridLayout":
            if "cellSize" in props:
                cs = props["cellSize"]
                lines.append(f"{var_name}.CellSize = UDim2.new({cs[0]}, {int(cs[1])}, {cs[2]}, {int(cs[3])})")
            if "cellPadding" in props:
                cp = props["cellPadding"]
                lines.append(f"{var_name}.CellPadding = UDim2.new({cp[0]}, {int(cp[1])}, {cp[2]}, {int(cp[3])})")
        if comp_type == "UIListLayout":
            fill_dir = props.get("fillDirection", "Vertical")
            lines.append(f"local fd = Enum.FillDirection.{fill_dir}")
            lines.append(f"{var_name}.FillDirection = fd")
            if "padding" in props:
                pad = props["padding"]
                if isinstance(pad, (list, tuple)) and len(pad) >= 2:
                    lines.append(f"{var_name}.Padding = UDim.new({pad[0]}, {int(pad[1])})")
                else:
                    lines.append(f"{var_name}.Padding = UDim.new(0, {int(pad)})")

        lines.append(f"{var_name}.Parent = {parent_var}")
        lines.append("")

        # Track interactive controls for behavior scripting
        if comp_type in ("TextButton", "ImageButton"):
            if "close" in name.lower():
                lines.append(f"table.insert(closeButtons, {var_name})")
            else:
                lines.append(f"table.insert(buttonsToAnimate, {var_name})")
        elif comp_type == "TextBox" and "search" in name.lower():
            lines.append(f"table.insert(searchBoxes, {var_name})")
        elif comp_type in ("ScrollingFrame", "Frame") and "grid" in name.lower():
            lines.append(f"table.insert(itemGrids, {var_name})")

        # Recurse children
        for child in el.get("children", []):
            if isinstance(child, dict):
                render_node(child, var_name)

    for child in gui_spec.get("children", []):
        if isinstance(child, dict):
            render_node(child, "screenGui")

    # Companion client behavior logic
    lines.extend([
        "-- ============================================",
        "-- CLIENT INTERACTIVITY CONTROLLER",
        "-- ============================================",
        "",
        "-- 1. Button Hover & Click Animations",
        "local tweenInfo = TweenInfo.new(0.15, Enum.EasingStyle.Quad, Enum.EasingDirection.Out)",
        "for _, btn in ipairs(buttonsToAnimate) do",
        "    local originalSize = btn.Size",
        "    local originalColor = btn.BackgroundColor3",
        "    btn.MouseEnter:Connect(function()",
        "        TweenService:Create(btn, tweenInfo, {",
        "            Size = UDim2.new(originalSize.X.Scale * 1.03, originalSize.X.Offset, originalSize.Y.Scale * 1.03, originalSize.Y.Offset)",
        "        }):Play()",
        "    end)",
        "    btn.MouseLeave:Connect(function()",
        "        TweenService:Create(btn, tweenInfo, {",
        "            Size = originalSize",
        "        }):Play()",
        "    end)",
        "    btn.MouseButton1Click:Connect(function()",
        '        print("[ForgeCraft] Clicked button:", btn.Name, btn.Parent and btn.Parent.Name or "")',
        "        -- Custom action hook / Purchase event",
        "    end)",
        "end",
        "",
        "-- 2. Close Buttons Dismissal",
        "for _, closeBtn in ipairs(closeButtons) do",
        "    closeBtn.MouseButton1Click:Connect(function()",
        "        screenGui.Enabled = false",
        '        print("[ForgeCraft] UI Closed")',
        "    end)",
        "end",
        "",
        "-- 3. Live Search Filtering",
        "for _, searchBox in ipairs(searchBoxes) do",
        "    searchBox:GetPropertyChangedSignal('Text'):Connect(function()",
        "        local query = string.lower(searchBox.Text)",
        "        for _, grid in ipairs(itemGrids) do",
        "            for _, item in ipairs(grid:GetChildren()) do",
        "                if item:IsA('Frame') then",
        "                    local itemNameLabel = item:FindFirstChild('ItemName')",
        "                    if itemNameLabel and itemNameLabel:IsA('TextLabel') then",
        "                        local itemName = string.lower(itemNameLabel.Text)",
        "                        item.Visible = query == '' or string.find(itemName, query, 1, true) ~= nil",
        "                    end",
        "                end",
        "            end",
        "        end",
        "    end)",
        "end",
        "",
        f'print("[ForgeCraft] {gui_name} loaded successfully!")',
        "return screenGui",
    ])

    return "\n".join(lines)



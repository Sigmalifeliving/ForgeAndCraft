"""Roblox Studio Output Exporter.

Converts ForgeCraft GUI JSON specification into:
1. Native Roblox Studio Model (.rbxm XML): can be imported directly into StarterGui via right-click -> "Insert from File..."
2. Standalone Luau Script (.luau): procedural generator script with client event handlers
3. Roblox Studio ZIP Package: bundle containing .rbxm, .luau, and README instructions
"""

import io
import json
import re
import uuid
import zipfile
import xml.etree.ElementTree as ET
from xml.dom import minidom
from typing import Any, Tuple


def _hex_to_rgb(hex_str: str) -> Tuple[float, float, float]:
    """Converts hex color string to 0.0-1.0 float RGB components for Roblox Color3."""
    clean = hex_str.strip().lstrip("#")
    if len(clean) == 3:
        clean = "".join(c * 2 for c in clean)
    if len(clean) != 6:
        return (0.1, 0.1, 0.15)
    try:
        r = int(clean[0:2], 16) / 255.0
        g = int(clean[2:4], 16) / 255.0
        b = int(clean[4:6], 16) / 255.0
        return (round(r, 4), round(g, 4), round(b, 4))
    except ValueError:
        return (0.1, 0.1, 0.15)


def _color3_luau(hex_str: str) -> str:
    """Returns Luau Color3.fromRGB(r, g, b) expression."""
    clean = hex_str.strip().lstrip("#")
    if len(clean) == 3:
        clean = "".join(c * 2 for c in clean)
    if len(clean) != 6:
        return "Color3.fromRGB(24, 24, 36)"
    try:
        r = int(clean[0:2], 16)
        g = int(clean[2:4], 16)
        b = int(clean[4:6], 16)
        return f"Color3.fromRGB({r}, {g}, {b})"
    except ValueError:
        return "Color3.fromRGB(24, 24, 36)"


